def cards(rows, kind: str = "", show_art: bool = True):
    parts = ['<div class="prod-grid">']
    for it in rows:
        art = (it.get("art") or "").strip()
        name = it["name"]
        if art.lower().startswith("руб") or art == "None":
            art = ""
        tip = it.get("sell") or sell_blurb(name, kind)
        art_html = f'<span class="art">арт. {H.escape(art)}</span>' if show_art and art else ""
        parts.append(
            "<article class=\"prod-card\">"
            f"<strong>{H.escape(name)}</strong>"
            f"{art_html}"
            f"<p class=\"how\">{H.escape(tip)}</p>"
            "</article>"
        )
    parts.append("</div>")
    return "\n".join(parts)


def metizy_mika():
    rows = []
    for it in ASSORT.get("МЕТИЗЫ", []):
        if "MIKA" not in it["name"].upper():
            continue
        art = it.get("art") or ""
        if art.lower().startswith("руб"):
            art = ""
        rows.append({"art": art, "name": it["name"]})
    return rows


def gcard(title: str, art: str, how: str) -> str:
    return (
        '<article class="prod-card">'
        f"<strong>{H.escape(title)}</strong>"
        f'<span class="art">{H.escape(art)}</span>'
        f'<p class="how">{H.escape(how)}</p>'
        "</article>"
    )


def ggrid(*parts: str) -> str:
    return '<div class="prod-grid">\n' + "\n".join(parts) + "\n</div>"


def grow(img: str, title: str, art: str, how: str, alt: str = "") -> str:
    """Photo + sell text stacked (no card frame)."""
    a = alt or title
    return (
        '<article class="prod-row">'
        f'<div class="prod-row-img"><img src="{H.escape(img)}" alt="{H.escape(a)}" loading="lazy" /></div>'
        '<div class="prod-row-body">'
        f"<strong>{H.escape(title)}</strong>"
        f'<span class="art">{H.escape(art)}</span>'
        f'<p class="how">{H.escape(how)}</p>'
        "</div></article>"
    )


def gstack(*parts: str) -> str:
    return '<div class="prod-stack">\n' + "\n".join(parts) + "\n</div>"


